import { formatPKR, formatDateTime } from './format';

export interface ExportColumnDef<T> {
  header: string;
  key?: keyof T | string;
  align?: 'left' | 'center' | 'right';
  format?: (row: T) => string;
  numeric?: boolean;
}

export interface ExportOptions<T> {
  title: string;
  subtitle?: string;
  periodLabel?: string;
  userName?: string;
  filename: string;
  columns: ExportColumnDef<T>[];
  data: T[];
  summaryRows?: Array<{ label: string; value: string | number }>;
}

export function exportToCSV<T>(options: ExportOptions<T>) {
  const { title, subtitle, periodLabel, userName, filename, columns, data, summaryRows } = options;

  const escapeCSV = (val: unknown) => {
    if (val == null) return '""';
    const s = String(val).replace(/"/g, '""');
    return `"${s}"`;
  };

  const lines: string[] = [];
  lines.push(escapeCSV(title));
  if (subtitle) lines.push(escapeCSV(subtitle));
  if (periodLabel) lines.push(escapeCSV(`Period: ${periodLabel}`));
  if (userName) lines.push(escapeCSV(`Generated by: ${userName} on ${new Date().toLocaleString('en-PK')}`));
  lines.push('');

  // Headers
  lines.push(columns.map((c) => escapeCSV(c.header)).join(','));

  // Rows
  data.forEach((row) => {
    const rowValues = columns.map((col) => {
      if (col.format) return escapeCSV(col.format(row));
      const val = col.key ? (row as any)[col.key] : '';
      return escapeCSV(val);
    });
    lines.push(rowValues.join(','));
  });

  // Summary Rows
  if (summaryRows && summaryRows.length > 0) {
    lines.push('');
    lines.push(escapeCSV('--- FINANCIAL SUMMARY ---'));
    summaryRows.forEach((s) => {
      lines.push(`${escapeCSV(s.label)},${escapeCSV(s.value)}`);
    });
  }

  const csvContent = lines.join('\r\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', `${filename}_${new Date().toISOString().slice(0, 10)}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export async function exportToExcel<T>(options: ExportOptions<T>) {
  const { title, subtitle, periodLabel, userName, filename, columns, data, summaryRows } = options;

  const XLSX = await import('xlsx');
  const wb = XLSX.utils.book_new();

  const aoaData: any[][] = [];
  aoaData.push([title]);
  if (subtitle) aoaData.push([subtitle]);
  if (periodLabel) aoaData.push([`Period: ${periodLabel}`]);
  if (userName) aoaData.push([`Generated by: ${userName} on ${new Date().toLocaleString('en-PK')}`]);
  aoaData.push([]);

  // Header row
  aoaData.push(columns.map((c) => c.header));

  // Data rows
  data.forEach((row) => {
    const rowValues = columns.map((col) => {
      if (col.format) return col.format(row);
      const val = col.key ? (row as any)[col.key] : '';
      if (col.numeric && val != null && !isNaN(Number(val))) {
        return Number(val);
      }
      return val ?? '—';
    });
    aoaData.push(rowValues);
  });

  // Summary rows
  if (summaryRows && summaryRows.length > 0) {
    aoaData.push([]);
    aoaData.push(['FINANCIAL SUMMARY TOTALS']);
    summaryRows.forEach((s) => {
      aoaData.push([s.label, s.value]);
    });
  }

  const ws = XLSX.utils.aoa_to_sheet(aoaData);
  ws['!cols'] = columns.map(() => ({ wch: 22 }));

  XLSX.utils.book_append_sheet(wb, ws, 'Financial Report');
  XLSX.writeFile(wb, `${filename}_${new Date().toISOString().slice(0, 10)}.xlsx`);
}

export function printFinancialReport<T>(options: ExportOptions<T>) {
  const { title, subtitle, periodLabel, userName, columns, data, summaryRows } = options;

  const popup = window.open('', '_blank', 'width=1150,height=800');
  if (!popup) {
    alert('Please allow popups to print or save report as PDF.');
    return;
  }

  const escapeHTML = (str: unknown) =>
    String(str ?? '').replace(/[&<>"']/g, (m) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[m] || m));

  const tableHeaders = columns
    .map((c) => `<th style="padding: 6px 10px; border: 1px solid #cbd5e1; background: #f8fafc; font-size: 11px; text-transform: uppercase; letter-spacing: 0.05em; text-align: ${c.align || 'left'}; color: #1e293b;">${escapeHTML(c.header)}</th>`)
    .join('');

  const tableRows = data
    .map((row) => {
      const cells = columns
        .map((col) => {
          const val = col.format ? col.format(row) : (col.key ? (row as any)[col.key] : '');
          return `<td style="padding: 6px 10px; border: 1px solid #e2e8f0; font-size: 12px; text-align: ${col.align || 'left'}; color: #334155;">${escapeHTML(val)}</td>`;
        })
        .join('');
      return `<tr style="page-break-inside: avoid;">${cells}</tr>`;
    })
    .join('');

  let summaryHTML = '';
  if (summaryRows && summaryRows.length > 0) {
    const summaryItems = summaryRows
      .map((s) => `<tr style="border-bottom: 1px solid #e2e8f0;"><td style="padding: 6px 12px; font-weight: 600; color: #1e293b;">${escapeHTML(s.label)}</td><td style="padding: 6px 12px; text-align: right; font-weight: 700; color: #0f766e;">${escapeHTML(s.value)}</td></tr>`)
      .join('');
    summaryHTML = `
      <div style="margin-top: 24px; max-width: 480px; margin-left: auto; border: 1px solid #cbd5e1; border-radius: 6px; overflow: hidden;">
        <div style="background: #f1f5f9; padding: 8px 12px; font-weight: bold; font-size: 11px; text-transform: uppercase; color: #0f172a; border-bottom: 1px solid #cbd5e1;">Financial Summary Statement</div>
        <table style="width: 100%; border-collapse: collapse; font-size: 12px;">${summaryItems}</table>
      </div>
    `;
  }

  const html = `
    <!DOCTYPE html>
    <html>
      <head>
        <title>${escapeHTML(title)}</title>
        <meta charset="utf-8" />
        <style>
          @page { size: landscape; margin: 12mm; }
          body { font-family: Inter, -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; color: #0f172a; margin: 0; padding: 16px; -webkit-print-color-adjust: exact; print-color-adjust: exact; }
          .report-header { border-bottom: 2px solid #0f766e; padding-bottom: 12px; margin-bottom: 16px; }
          .report-title { font-size: 18px; font-weight: 800; color: #0f766e; margin: 0; }
          .report-subtitle { font-size: 12px; color: #64748b; margin-top: 4px; }
          .meta-bar { display: flex; justify-content: space-between; font-size: 11px; color: #475569; margin-top: 8px; }
          table.data-table { width: 100%; border-collapse: collapse; margin-top: 8px; }
          @media print {
            body { padding: 0; }
            button { display: none; }
          }
        </style>
      </head>
      <body>
        <div class="report-header">
          <h1 class="report-title">${escapeHTML(title)}</h1>
          ${subtitle ? `<div class="report-subtitle">${escapeHTML(subtitle)}</div>` : ''}
          <div class="meta-bar">
            <span><strong>Period:</strong> ${escapeHTML(periodLabel || 'All Recorded')}</span>
            <span><strong>Generated:</strong> ${escapeHTML(new Date().toLocaleString('en-PK'))} ${userName ? `· by ${escapeHTML(userName)}` : ''}</span>
          </div>
        </div>
        <table class="data-table">
          <thead><tr>${tableHeaders}</tr></thead>
          <tbody>${tableRows}</tbody>
        </table>
        ${summaryHTML}
      </body>
    </html>
  `;

  popup.document.write(html);
  popup.document.close();
  popup.focus();
  setTimeout(() => {
    popup.print();
  }, 250);
}
